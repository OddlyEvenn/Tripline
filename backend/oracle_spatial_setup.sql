-- =====================================================================
--  ROBUST ORACLE SPATIAL SETUP FOR TRIPLINE STATIONS
-- =====================================================================

-- 1. DROP THE TABLE COMPLETELY to ensure a clean state (WARNING: Data will be lost)
-- This is often the safest way to reset spatial metadata and indexes.
BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE stations CASCADE CONSTRAINTS';
EXCEPTION
   WHEN OTHERS THEN
      IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

-- 2. CREATE THE TABLE WITH SDO_GEOMETRY
CREATE TABLE stations (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(255) NOT NULL,
    city VARCHAR2(255) NOT NULL,
    state VARCHAR2(255),
    country VARCHAR2(255) DEFAULT 'India',
    type VARCHAR2(30) NOT NULL,
    location MDSYS.SDO_GEOMETRY,
    is_active NUMBER(1) DEFAULT 1
);

-- 3. REGISTER METADATA
DELETE FROM USER_SDO_GEOM_METADATA 
WHERE TABLE_NAME = 'STATIONS' AND COLUMN_NAME = 'LOCATION';

INSERT INTO USER_SDO_GEOM_METADATA (TABLE_NAME, COLUMN_NAME, DIMINFO, SRID)
VALUES ('STATIONS', 'LOCATION',
  MDSYS.SDO_DIM_ARRAY(
    MDSYS.SDO_DIM_ELEMENT('X', -180, 180, 0.05),
    MDSYS.SDO_DIM_ELEMENT('Y', -90, 90, 0.05)
  ),
  4326 -- SRID for WGS84
);

-- 4. CREATE SPATIAL INDEX
-- If the previous error was ORA-00955, dropping the table above fixed it.
CREATE INDEX stations_spx ON stations(location) 
INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;

COMMIT;

-- VERIFICATION
SELECT * FROM USER_SDO_GEOM_METADATA WHERE TABLE_NAME = 'STATIONS';
